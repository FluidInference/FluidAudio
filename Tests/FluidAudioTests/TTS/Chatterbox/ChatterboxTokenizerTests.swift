final class ChatterboxTokenizerTests: XCTestCase {

    private var tmpDir: URL!

    override func setUpWithError() throws {
        try super.setUpWithError()
        tmpDir = FileManager.default.temporaryDirectory
            .appendingPathComponent("ChatterboxTokenizerTests-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: tmpDir, withIntermediateDirectories: true)
    }

    override func tearDownWithError() throws {
        if let tmpDir, FileManager.default.fileExists(atPath: tmpDir.path) {
            try FileManager.default.removeItem(at: tmpDir)
        }
        try super.tearDownWithError()
    }

    // MARK: - puncNorm

    func testPuncNormAddsTrailingStopAndCapitalizes() {
        XCTAssertEqual(ChatterboxTokenizer.puncNorm("hello world"), "Hello world.")
        XCTAssertEqual(ChatterboxTokenizer.puncNorm("Done!"), "Done!")
        XCTAssertEqual(
            ChatterboxTokenizer.puncNorm(""),
            "You need to add some text for me to talk.")
    }

    func testPuncNormReplacesLlmPunctuation() {
        // Upstream collapses whitespace BEFORE the punctuation replacements,
        // so ", " insertions legitimately produce double spaces — verified
        // against the Python reference (and the [7,2,2] double-SPACE ids in
        // the parity vectors below).
        XCTAssertEqual(
            ChatterboxTokenizer.puncNorm("wait; ok… fine — yes"),
            "Wait,  ok,  fine - yes.")
        XCTAssertEqual(ChatterboxTokenizer.puncNorm("a  b   c"), "A b c.")
    }

    // MARK: - Mechanics on a small synthetic vocab

    private func makeTinyTokenizer() throws -> ChatterboxTokenizer {
        let json: [String: Any] = [
            "added_tokens": [
                ["id": 2, "content": "[SPACE]"],
                ["id": 100, "content": "[en]"],
            ],
            "model": [
                "type": "BPE",
                "vocab": [
                    "[UNK]": 1, "a": 10, "b": 11, "c": 12, "ab": 20, "abc": 21, ".": 30,
                ],
                "merges": ["a b", "ab c"],
            ],
        ]
        let url = tmpDir.appendingPathComponent("tiny.json")
        try JSONSerialization.data(withJSONObject: json).write(to: url)
        return try ChatterboxTokenizer(tokenizerJsonURL: url)
    }

    func testAddedTokenSplitAndBpeMergeOrder() throws {
        let tokenizer = try makeTinyTokenizer()
        // "[en]" prefix + "abc ab." → added(100), abc→21, SPACE(2), ab→20, .→30
        XCTAssertEqual(tokenizer.encode("abc ab.", languageId: "en"), [100, 21, 2, 20, 30])
    }

    func testUnknownCharactersMapToUnk() throws {
        let tokenizer = try makeTinyTokenizer()
        XCTAssertEqual(tokenizer.encode("q", languageId: "en"), [100, 1])
    }

