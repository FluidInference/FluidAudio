    func testRealVocabParityVectors() throws {
        let cached = try? TtsCacheDirectory.ensure()
            .appendingPathComponent("Models")
            .appendingPathComponent(Repo.chatterbox.folderName)
            .appendingPathComponent(ModelNames.Chatterbox.tokenizerFile)
        guard let cached, FileManager.default.fileExists(atPath: cached.path) else {
            throw XCTSkip("Chatterbox tokenizer asset not downloaded")
        }
        let tokenizer = try ChatterboxTokenizer(tokenizerJsonURL: cached)
        for (lang, text, expected) in Self.vectors {
            let normalized = ChatterboxTokenizer.puncNorm(text)
            XCTAssertEqual(
                tokenizer.encode(normalized, languageId: lang), expected,
                "mismatch for \(lang): \(text)")
        }
